    private void jMenuItem6ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItem6ActionPerformed
        try {
            DB_CONNECTION db = new DB_CONNECTION();
            String CheckQuery = "SELECT * FROM stock_detail";
            db.Pstmt = db.Con.prepareStatement(CheckQuery);
            db.Rst = db.Pstmt.executeQuery();

            // Check if there are records
            if (db.Rst.isBeforeFirst()) {
                SUDStockView.setVisible(true);

                // Clear existing items before adding new ones
                SUDStockInput.removeAllItems();
                SUDStockInput.addItem("Select Stock"); // Optional first item

                // Add values from the database
                while (db.Rst.next()) {
                    SUDStockInput.addItem(db.Rst.getString(1)); // Column 1 value
                }
            } else {
                JOptionPane.showMessageDialog(this, "Sorry, there is no medicine stock found!");
            }

            // Close resources to prevent memory leaks
            db.Rst.close();
            db.Pstmt.close();
            db.Con.close();
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_jMenuItem6ActionPerformed

