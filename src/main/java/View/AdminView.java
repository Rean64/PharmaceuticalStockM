    private void SearchMedicineBtnupdateMedicineActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SearchMedicineBtnupdateMedicineActionPerformed
        String StrSearchUpdateDeleteMedicine = SUDMedicineInput.getText();
        if (StrSearchUpdateDeleteMedicine.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter Medicine Name");
        } else {
            try {
                DB_CONNECTION db = new DB_CONNECTION();
                String Query = "select * from medications where med_name=?";
                db.Pstmt = db.Con.prepareStatement(Query);
                db.Pstmt.setString(1, StrSearchUpdateDeleteMedicine);
                db.Rst = db.Pstmt.executeQuery();

                if (db.Rst.isBeforeFirst()) {
                    SearchMedicineView.setVisible(true);
                    SUDMedicineView.setVisible(false);
                    while (db.Rst.next()) {
                        SearchMedicineNameInput.setText(db.Rst.getString(1));
                        SearchCompanyNameInput.setText(db.Rst.getString(2));
                        SearchMedicinFormulaInput.setText(db.Rst.getString(3));
                        SearchMedicineSuplierInput.setText(db.Rst.getString(4));
                        SearchCompanyContactInput.setText(db.Rst.getString(5));
                        SearchSuplierContactInput.setText(db.Rst.getString(6));
                        SearchMedicinPurposeInput.setText(db.Rst.getString(7));
                    }
                } else {
                    JOptionPane.showMessageDialog(this, "Medicine Not Found! Please Enter correct Medicine Name");
                }

            } catch (HeadlessException | SQLException e) {
            }
        }
    }//GEN-LAST:event_SearchMedicineBtnupdateMedicineActionPerformed

