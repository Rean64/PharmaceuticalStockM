    private void ChangePasswordSubmitBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ChangePasswordSubmitBtnActionPerformed
        String OldPsswd = OldPasswordInput.getText(), NewPsswd = NewPasswordInput.getText(), CnfPsswd = ConfirmPasswordInput.getText(), Email = EmailInput.getText();
        try {
            DB_CONNECTION db = new DB_CONNECTION();
            String CheckQuery = "Select * from user where email=? AND password=?",
                    UpdateQuery = "update user set password=? where password=?";
            db.Pstmt = db.Con.prepareStatement(CheckQuery);
            
            db.Pstmt.setString(1, Email);
            db.Pstmt.setString(2, OldPsswd);
            db.Rst = db.Pstmt.executeQuery();
            if (db.Rst.next()) {
                if (NewPsswd.equals(CnfPsswd)) {
                    db.Pstmt = db.Con.prepareStatement(UpdateQuery);
                    db.Pstmt.setString(1, NewPsswd);
                    db.Pstmt.setString(2, OldPsswd);
                    int i = db.Pstmt.executeUpdate();
                    if (i > 0) {
                        JOptionPane.showMessageDialog(this, "Successfully Password Updated");
                        OldPasswordInput.setText("");
                        NewPasswordInput.setText("");
                        ConfirmPasswordInput.setText("");
                        EmailInput.setText("");

//                        this.setVisible(false);
//                        new Login().setVisible(true);
                    } else {
                        JOptionPane.showMessageDialog(this, "Error! In Password Updation");
                    }
                } else {
                    JOptionPane.showMessageDialog(this, "New Password And Confirm Password Not Matched");
                }
            } else {
                JOptionPane.showMessageDialog(this, "Old Password Is Incorrect! Plese Enter Correct Old Password");
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_ChangePasswordSubmitBtnActionPerformed

