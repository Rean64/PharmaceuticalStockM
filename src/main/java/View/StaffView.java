    private void DeleteMedicineOBtnupdateMedicineActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteMedicineOBtnupdateMedicineActionPerformed
        String Med_Name = DeleteMedicineNameInput.getText();
        try {
            DB_CONNECTION db = new DB_CONNECTION();
            int dialogResult = JOptionPane.showConfirmDialog (null, "Do you want to Delete This Medicine","Warning",JOptionPane.YES_NO_OPTION);
            if(dialogResult == JOptionPane.YES_OPTION){
            String Query = "delete from medications where med_name=?";
            db.Pstmt = db.Con.prepareStatement(Query);
            db.Pstmt.setString(1, Med_Name);
            int i = db.Pstmt.executeUpdate();
            if (i > 0) {
                JOptionPane.showMessageDialog(this, "Medicine Has Been Deleted Successfully");
                DeleteMedicineView.setVisible(false);
                SearchUpdateDeleteMedicineView.setVisible(true);
            } else {
                JOptionPane.showMessageDialog(this, "Error In Medicine Deletion");
            }
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_DeleteMedicineOBtnupdateMedicineActionPerformed

