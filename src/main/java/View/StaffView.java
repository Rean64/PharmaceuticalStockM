    private void AddMedicineBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AddMedicineBtnActionPerformed
        String Med_Name = AddMedicineNameInput.getText(), Comp_Name = AddCompanyNameInput
                .getText(), Med_Formla = AddMedicinFormulaInput.getText(), Med_Sup = AddMedicineSuplierInput.getText(), Comp_Cont = AddCompanyContactInput.getText(), Sup_Cont = AddSuplierContactInput.getText(), Med_Purpose = AddMedicinePurposeInput.getText();
        if (Med_Name.trim().isEmpty() || Comp_Name.trim().isEmpty() || Med_Formla.trim().isEmpty() || Med_Sup.trim().isEmpty() || Comp_Cont.trim().isEmpty() || Sup_Cont.trim().isEmpty() || Med_Purpose.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Fill The Required Fields");
        } else {
            try {
                DB_CONNECTION db = new DB_CONNECTION();
                String CheckQuery = "select * from medications where med_name=?";
                String InsertQuery = "insert into medications(med_name, med_company, med_formula, med_sup, comp_contact, sup_contact, med_purpose) values(?, ?, ?, ?, ?, ?, ?)";
                db.Pstmt = db.Con.prepareStatement(CheckQuery);
                db.Pstmt.setString(1, Med_Name);
                db.Rst = db.Pstmt.executeQuery();
                if (db.Rst.isBeforeFirst()) {
                    JOptionPane.showMessageDialog(this, "This Medicine Already Exist in Your Store");
                } else {
                    db.Pstmt = db.Con.prepareStatement(InsertQuery);
                    db.Pstmt.setString(1, Med_Name);
                    db.Pstmt.setString(2, Comp_Name);
                    db.Pstmt.setString(3, Med_Formla);
                    db.Pstmt.setString(4, Med_Sup);
                    db.Pstmt.setString(5, Comp_Cont);
                    db.Pstmt.setString(6, Sup_Cont);
                    db.Pstmt.setString(7, Med_Purpose);
                    int i = db.Pstmt.executeUpdate();
                    if (i > 0) {
                        JOptionPane.showMessageDialog(this, "This Medicine Successfully Added");
                        AddMedicineNameInput.setText("");
                        AddCompanyNameInput.setText("");
                        AddMedicinFormulaInput.setText("");
                        AddMedicineSuplierInput.setText("");
                        AddCompanyContactInput.setText("");
                        AddSuplierContactInput.setText("");
                        AddMedicinePurposeInput.setText("");
                    } else {
                        JOptionPane.showMessageDialog(this, "Error In Add New medicine");
                    }
                }

            } catch (Exception e) {
                e.printStackTrace();
            }
        }
    }//GEN-LAST:event_AddMedicineBtnActionPerformed

