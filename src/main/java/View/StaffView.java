    private void SearchMedicineByNameInputKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_SearchMedicineByNameInputKeyReleased
        try {
            DB_CONNECTION db = new DB_CONNECTION();
            String Query = "select * from medications where med_name like ?";
            db.Pstmt = db.Con.prepareStatement(Query);
            db.Pstmt.setString(1, SearchMedicineByNameInput.getText() + "%");
            db.Rst = db.Pstmt.executeQuery();
            if (db.Rst.isBeforeFirst()) {
                ViewMedicineListView.setVisible(true);
                Vector<String> header = new Vector<>();
                Vector<Vector<String>> data = new Vector<>();
                header.add("Medicine Name");
                header.add("Company Name");
                header.add("Medicine Formula");
                header.add("Medicine Suplier");
                header.add("Company Contact");
                header.add("Suplier Contact");
                header.add("Medicine Purpose");
                while (db.Rst.next()) {
                    Vector<String> temp = new Vector<>();
                    temp.add(db.Rst.getString(1));
                    temp.add(db.Rst.getString(2));
                    temp.add(db.Rst.getString(3));
                    temp.add(db.Rst.getString(4));
                    temp.add(db.Rst.getString(5));
                    temp.add(db.Rst.getString(6));
                    temp.add(db.Rst.getString(7));
                    data.add(temp);
                }
                MedicineTable.setModel(new DefaultTableModel(data, header));
            } else {
                JOptionPane.showMessageDialog(this, "Now There Is No Medicine");
            }

        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_SearchMedicineByNameInputKeyReleased

