    private void UpdateMedicineOBtnupdateMedicineActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_UpdateMedicineOBtnupdateMedicineActionPerformed
        String Med_Name = UpdateMedicineNameInput.getText(), Comp_Name = UpdateCompanyNameInput
                .getText(), Med_Formla = UpdateMedicinFormulaInput.getText(), Med_Sup = UpdateMedicineSuplierInput.getText(), Comp_Cont = UpdateCompanyContactInput.getText(), Sup_Cont = UpdateSuplierContactInput.getText(), Med_Purpose = UpdateMedicinePurposeInput.getText();
        if (Med_Name.trim().isEmpty() || Comp_Name.trim().isEmpty() || Med_Formla.trim().isEmpty() || Med_Sup.trim().isEmpty() || Comp_Cont.trim().isEmpty() || Sup_Cont.trim().isEmpty() || Med_Purpose.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Fill And Select All The Required Fields");
        } else {
            try {
                DB_CONNECTION db = new DB_CONNECTION();
                String InsertQuery = "update medications set med_name=?, med_company=?, med_formula=?, med_sup=?, comp_contact=?, sup_contact=?, med_purpose=? where med_name=?";
                db.Pstmt = db.Con.prepareStatement(InsertQuery);
                db.Pstmt.setString(1, Med_Name);
                db.Pstmt.setString(2, Comp_Name);
                db.Pstmt.setString(3, Med_Formla);
                db.Pstmt.setString(4, Med_Sup);
                db.Pstmt.setString(5, Comp_Cont);
                db.Pstmt.setString(6, Sup_Cont);
                db.Pstmt.setString(7, Med_Purpose);
                db.Pstmt.setString(8, Med_Name);
                int i = db.Pstmt.executeUpdate();
                if (i > 0) {
                    JOptionPane.showMessageDialog(this, "Medicine Successfully Updated");
                } else {
                    JOptionPane.showMessageDialog(this, "Error In Updation Medicine");
                }

            } catch (Exception e) {
                e.printStackTrace();
            }
        }
    }//GEN-LAST:event_UpdateMedicineOBtnupdateMedicineActionPerformed

